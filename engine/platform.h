#pragma once

#include "input.h"

#include <optional>
#include <string>
#include <vector>

// Единая граница между игровой логикой и операционной системой.
// Игровой код вызывает эти функции, а CMake подключает реализацию
// только для выбранной платформы: Windows или Linux/X11.
namespace Platform
{
// Данные ошибки не зависят от Win32/X11. Наличие ошибки определяется результатом операции.
struct Error
{
    std::string operation;
    std::string message;
    std::optional<int> nativeCode;
};

// Всегда пишет в stderr; в Windows дополнительно показывает MessageBox, если showDialog == true.
// Для некритичных ошибок и ошибок очистки диалог можно отключить.
void reportError(const Error& error, bool showDialog = true);

// Отдельные клавиши без назначения игровых действий и без объединения WASD со стрелками.
using Key = Engine::Key;

struct WindowOptions
{
    int width = 800;
    int height = 600;
    // Ноль не добавляет ограничений движка к ограничениям оконной системы.
    int minimumWidth = 0;
    int minimumHeight = 0;
    // false запрещает пользователю менять размер окна и разворачивать его на весь экран.
    bool resizable = true;
    // Заголовки передаются в UTF-8; пустая строка допустима.
    std::string title = "Application";
};

struct WindowState
{
    int width = 0;
    int height = 0;
    bool focused = false;
    bool minimized = false;
};

// Создаёт окно и контекст OpenGL. Размеры клиентской области задаются в пикселях.
// Начальный viewport занимает всю клиентскую область.
// errors заменяется результатом операции: сначала основная ошибка, затем ошибки автоматической очистки.
// При неудачном запуске выполняется очистка; повторный initialize() допустим без shutdown().
// Начальные размеры положительные, минимальные — неотрицательные и не больше начальных.
// Общий предел 65535 пикселей соответствует размерным полям протокола X11.
// Повторная инициализация работающей платформы отклоняется без изменения её состояния.
// Все функции платформы вызываются в одном потоке; поддерживается одно окно.
bool initialize(const WindowOptions& options, std::vector<Error>& errors);

// Возвращает сохранённые размеры клиентской области и состояние окна без обращений к ОС.
// Начальный снимок создаётся при initialize(), затем обновляется обработчиками событий ОС
// (обычно во время processEvents()). До обработки новых событий возвращается прежний снимок.
// При ошибке state не меняется; после уничтожения окна возвращается пустой снимок до shutdown().
bool getWindowState(WindowState& state, Error& error);

// Меняет заголовок окна. UTF-8 без встроенных нулей; некорректная строка отклоняется.
bool setWindowTitle(const std::string& title, Error& error);

// Обрабатывает события и обновляет снимок окна. false означает ошибку обработки.
// При изменении размеров обновляет viewport на всю клиентскую область, не меняя матрицы OpenGL.
// Запрос закрытия читается отдельно через isCloseRequested(); нажатия клавиш не закрывают окно.
bool processEvents(Error& error);

// Отдельно хранит запрос выхода, обнаруженный при обработке событий.
// Чтение не обрабатывает события. До инициализации и после shutdown() возвращает false.
// Обнаруженный запрос сохраняется до shutdown(), даже при последующей ошибке обработки событий.
bool isCloseRequested();

// Проверяет удержание по снимку, опубликованному последним processEvents().
// Потеря фокуса, сворачивание и уничтожение окна сбрасывают удержание при публикации
// соответствующих событий. До следующего processEvents() сохраняется прежний снимок,
// даже если сообщение Win32 уже пришло синхронно. Для неизвестной клавиши — false.
bool isKeyDown(Key key);
bool isKeyPressed(Key key);
bool isKeyReleased(Key key);

// Снимок и упорядоченные события последнего processEvents; ссылки действуют до
// следующего processEvents/initialize/shutdown. Один вызов processEvents — один кадр ввода.
// pressed/released, текст, движение и колесо очищаются каждый кадр, down сохраняется.
// До запуска и после shutdown возвращаются пустые данные. Читать можно многократно.
const Engine::InputState& getInput();
const std::vector<Engine::Event>& getEvents();

// Показывает нарисованный кадр из заднего буфера окна.
// Для свёрнутого окна пропускает обмен буферов и возвращает true.
bool present(Error& error);

// Освобождает созданные ресурсы ОС и графической подсистемы.
// Продолжает очистку после отказа отдельной операции; заменяет errors списком ошибок этого вызова.
void shutdown(std::vector<Error>& errors);
}
