inline unsigned int debugGlyph(char character)
{
    static constexpr std::array<unsigned int, 36> Glyphs = {
        0b010'101'111'101'101, 0b110'101'110'101'110, 0b011'100'100'100'011,
        0b110'101'101'101'110, 0b111'100'110'100'111, 0b111'100'110'100'100,
        0b011'100'101'101'011, 0b101'101'111'101'101, 0b111'010'010'010'111,
        0b001'001'001'101'010, 0b101'101'110'101'101, 0b100'100'100'100'111,
        0b101'111'111'101'101, 0b101'111'111'111'101, 0b010'101'101'101'010,
        0b110'101'110'100'100, 0b010'101'101'111'011, 0b110'101'110'101'101,
        0b011'100'010'001'110, 0b111'010'010'010'010, 0b101'101'101'101'111,
        0b101'101'101'101'010, 0b101'101'111'111'101, 0b101'101'010'101'101,
        0b101'101'010'010'010, 0b111'001'010'100'111,
        0b111'101'101'101'111, 0b010'110'010'010'111, 0b110'001'111'100'111,
        0b110'001'110'001'110, 0b101'101'111'001'001, 0b111'100'110'001'110,
        0b011'100'111'101'111, 0b111'001'010'010'010, 0b111'101'111'101'111,
        0b111'101'111'001'110
    };
    unsigned int glyph = 0;
    if (character >= 'A' && character <= 'Z') {
        glyph = Glyphs[static_cast<std::size_t>(character - 'A')];
    } else if (character >= '0' && character <= '9') {
        glyph = Glyphs[26 + static_cast<std::size_t>(character - '0')];
    } else if (character == '-') {
        glyph = 0b000'000'111'000'000;
    } else if (character == '+') {
        glyph = 0b000'010'111'010'000;
    } else if (character == '/') {
        glyph = 0b001'001'010'100'100;
    }
    return glyph;
}
// Латиница сохраняет прежние метрики 3x5; русские буквы используют 5x7.
struct DebugGlyph
{
    std::uint64_t bits = 0;
    int width = 3;
    int height = 5;
};

inline DebugGlyph unicodeDebugGlyph(std::uint32_t code)
{
    if (code >= 'a' && code <= 'z') {
        code -= 'a' - 'A';
    }
    if (code >= 0x430 && code <= 0x44f) {
        code -= 0x20;
    }
    if (code == 0x451) {
        code = 0x401;
    }
    static constexpr std::array<std::uint64_t, 32> Russian = {
        0b01110'10001'10001'11111'10001'10001'10001ULL,
        0b11111'10000'10000'11110'10001'10001'11110ULL,
        0b11110'10001'10001'11110'10001'10001'11110ULL,
        0b11111'10000'10000'10000'10000'10000'10000ULL,
        0b00110'01010'01010'01010'10010'11111'10001ULL,
        0b11111'10000'10000'11110'10000'10000'11111ULL,
        0b10101'10101'01110'00100'01110'10101'10101ULL,
        0b01110'10001'00001'00110'00001'10001'01110ULL,
        0b10001'10001'10011'10101'11001'10001'10001ULL,
        0b01010'00100'10001'10011'10101'11001'10001ULL,
        0b10001'10010'10100'11000'10100'10010'10001ULL,
        0b00111'01001'01001'01001'01001'01001'10001ULL,
        0b10001'11011'10101'10101'10001'10001'10001ULL,
        0b10001'10001'10001'11111'10001'10001'10001ULL,
        0b01110'10001'10001'10001'10001'10001'01110ULL,
        0b11111'10001'10001'10001'10001'10001'10001ULL,
        0b11110'10001'10001'11110'10000'10000'10000ULL,
        0b01111'10000'10000'10000'10000'10000'01111ULL,
        0b11111'00100'00100'00100'00100'00100'00100ULL,
        0b10001'10001'10001'01111'00001'10001'01110ULL,
        0b00100'01110'10101'10101'10101'01110'00100ULL,
        0b10001'10001'01010'00100'01010'10001'10001ULL,
        0b10010'10010'10010'10010'10010'11111'00001ULL,
        0b10001'10001'10001'01111'00001'00001'00001ULL,
        0b10101'10101'10101'10101'10101'10101'11111ULL,
        0b10101'10101'10101'10101'10101'11111'00001ULL,
        0b11000'01000'01000'01110'01001'01001'01110ULL,
        0b10001'10001'10001'11001'10101'10101'11001ULL,
        0b10000'10000'10000'11110'10001'10001'11110ULL,
        0b01110'10001'00001'00111'00001'10001'01110ULL,
        0b10010'10101'10101'11101'10101'10101'10010ULL,
        0b01111'10001'10001'01111'00101'01001'10001ULL
    };
    if (code >= 0x410 && code <= 0x42f) {
        return {Russian[code - 0x410], 5, 7};
    }
    if (code == 0x401) {
        return {0b01010'00000'11111'10000'11110'10000'11111ULL, 5, 7};
    }
    if (code == '.') {
        return {0b000'000'000'000'010, 3, 5};
    }
    if (code == ':') {
        return {0b000'010'000'010'000, 3, 5};
    }
    if (code == '%') {
        return {0b101'001'010'100'101, 3, 5};
    }
    return {code < 128 ? debugGlyph(static_cast<char>(code)) : 0, 3, 5};
}
