#pragma once

#include <array>
#include <cstddef>
#include <cstdint>

namespace Engine::Detail
{
struct DebugGlyph
{
    std::uint64_t bits = 0;
    int width = 5;
    int height = 7;
};

inline DebugGlyph unicodeDebugGlyph(std::uint32_t code)
{
    if (code >= 'a' && code <= 'z') {
        code -= 'a' - 'A';
    }
    if (code >= 0x430 && code <= 0x44f) {
        code -= 0x20;
    }
    if (code == 0x451) {
        code = 0x401;
    }
    static constexpr std::array<std::uint64_t, 32> Russian = {
        0b01110'10001'10001'11111'10001'10001'10001ULL,
        0b11111'10000'10000'11110'10001'10001'11110ULL,
        0b11110'10001'10001'11110'10001'10001'11110ULL,
        0b11111'10000'10000'10000'10000'10000'10000ULL,
        0b00110'01010'01010'01010'10010'11111'10001ULL,
        0b11111'10000'10000'11110'10000'10000'11111ULL,
        0b10101'10101'01110'00100'01110'10101'10101ULL,
        0b01110'10001'00001'00110'00001'10001'01110ULL,
        0b10001'10001'10011'10101'11001'10001'10001ULL,
        0b01010'00100'10001'10011'10101'11001'10001ULL,
        0b10001'10010'10100'11000'10100'10010'10001ULL,
        0b00111'01001'01001'01001'01001'01001'10001ULL,
        0b10001'11011'10101'10101'10001'10001'10001ULL,
        0b10001'10001'10001'11111'10001'10001'10001ULL,
        0b01110'10001'10001'10001'10001'10001'01110ULL,
        0b11111'10001'10001'10001'10001'10001'10001ULL,
        0b11110'10001'10001'11110'10000'10000'10000ULL,
        0b01111'10000'10000'10000'10000'10000'01111ULL,
        0b11111'00100'00100'00100'00100'00100'00100ULL,
        0b10001'10001'10001'01111'00001'10001'01110ULL,
        0b00100'01110'10101'10101'10101'01110'00100ULL,
        0b10001'10001'01010'00100'01010'10001'10001ULL,
        0b10010'10010'10010'10010'10010'11111'00001ULL,
        0b10001'10001'10001'01111'00001'00001'00001ULL,
        0b10101'10101'10101'10101'10101'10101'11111ULL,
        0b10101'10101'10101'10101'10101'11111'00001ULL,
        0b11000'01000'01000'01110'01001'01001'01110ULL,
        0b10001'10001'10001'11001'10101'10101'11001ULL,
        0b10000'10000'10000'11110'10001'10001'11110ULL,
        0b01110'10001'00001'00111'00001'10001'01110ULL,
        0b10010'10101'10101'11101'10101'10101'10010ULL,
        0b01111'10001'10001'01111'00101'01001'10001ULL
    };
    if (code >= 0x410 && code <= 0x42f) {
        return {Russian[code - 0x410], 5, 7};
    }
    if (code == 0x401) {
        return {0b01010'00000'11111'10000'11110'10000'11111ULL, 5, 7};
    }
    static constexpr std::array<std::uint64_t, 36> LatinAndDigits = {
        0b01110'10001'10001'11111'10001'10001'10001ULL,
        0b11110'10001'10001'11110'10001'10001'11110ULL,
        0b01111'10000'10000'10000'10000'10000'01111ULL,
        0b11110'10001'10001'10001'10001'10001'11110ULL,
        0b11111'10000'10000'11110'10000'10000'11111ULL,
        0b11111'10000'10000'11110'10000'10000'10000ULL,
        0b01110'10001'10000'10111'10001'10001'01110ULL,
        0b10001'10001'10001'11111'10001'10001'10001ULL,
        0b11111'00100'00100'00100'00100'00100'11111ULL,
        0b00111'00010'00010'00010'10010'10010'01100ULL,
        0b10001'10010'10100'11000'10100'10010'10001ULL,
        0b10000'10000'10000'10000'10000'10000'11111ULL,
        0b10001'11011'10101'10101'10001'10001'10001ULL,
        0b10001'11001'10101'10011'10001'10001'10001ULL,
        0b01110'10001'10001'10001'10001'10001'01110ULL,
        0b11110'10001'10001'11110'10000'10000'10000ULL,
        0b01110'10001'10001'10001'10101'10010'01101ULL,
        0b11110'10001'10001'11110'10100'10010'10001ULL,
        0b01111'10000'10000'01110'00001'00001'11110ULL,
        0b11111'00100'00100'00100'00100'00100'00100ULL,
        0b10001'10001'10001'10001'10001'10001'01110ULL,
        0b10001'10001'10001'10001'10001'01010'00100ULL,
        0b10001'10001'10001'10101'10101'11011'10001ULL,
        0b10001'10001'01010'00100'01010'10001'10001ULL,
        0b10001'10001'01010'00100'00100'00100'00100ULL,
        0b11111'00001'00010'00100'01000'10000'11111ULL,
        0b01110'10001'10011'10101'11001'10001'01110ULL,
        0b00100'01100'00100'00100'00100'00100'01110ULL,
        0b01110'10001'00001'00010'00100'01000'11111ULL,
        0b11110'00001'00001'01110'00001'00001'11110ULL,
        0b00010'00110'01010'10010'11111'00010'00010ULL,
        0b11111'10000'10000'11110'00001'00001'11110ULL,
        0b01110'10000'10000'11110'10001'10001'01110ULL,
        0b11111'00001'00010'00100'01000'01000'01000ULL,
        0b01110'10001'10001'01110'10001'10001'01110ULL,
        0b01110'10001'10001'01111'00001'00001'01110ULL
    };
    if (code >= 'A' && code <= 'Z') {
        return {LatinAndDigits[code - 'A'], 5, 7};
    }
    if (code >= '0' && code <= '9') {
        return {LatinAndDigits[26 + code - '0'], 5, 7};
    }
    switch (code) {
        case '-': return {0b00000'00000'00000'11111'00000'00000'00000ULL, 5, 7};
        case '+': return {0b00000'00100'00100'11111'00100'00100'00000ULL, 5, 7};
        case '/': return {0b00001'00001'00010'00100'01000'10000'10000ULL, 5, 7};
        case '.': return {0b00000'00000'00000'00000'00000'00110'00110ULL, 5, 7};
        case ':': return {0b00000'00110'00110'00000'00110'00110'00000ULL, 5, 7};
        case '%': return {0b11001'11010'00010'00100'01000'01011'10011ULL, 5, 7};
        default: return {};
    }
}
}
