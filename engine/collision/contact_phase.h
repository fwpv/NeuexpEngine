#pragma once

namespace NeuexpEngine
{
// Фаза контакта пары: общая для событий сцены и физического мира.
enum class ContactPhase
{
    // Пара появилась в этом вызове.
    Begin,
    // Пара была в прошлом вызове и остаётся; данные контакта относятся к этому вызову.
    Persist,
    // Пара исчезла: формы разошлись, пара запрещена, объект или тело удалено.
    End
};
}
